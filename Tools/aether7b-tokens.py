"""Generate Aether7b design tokens for the macOS (Swift) and Linux (Rust) UIs.

Reads Shared/Design/aether7b.tokens.json (vendored from the Aether7b design
system) and writes XRGCore/XRGAether7b.swift and xrg-linux/rust/src/ui/aether7b.rs.
Run with --check to verify the generated files are current instead of writing.
"""
import argparse
import difflib
import json
import math
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / "Shared/Design/aether7b.tokens.json"
SWIFT = ROOT / "XRGCore/XRGAether7b.swift"
RUST = ROOT / "xrg-linux/rust/src/ui/aether7b.rs"

SOURCE_NOTE = "aether7b v1.1 3bc86b3"

# (generated role name, path in the token file) for every adaptive colour role.
ADAPTIVE_ROLES = [
    ("bgCanvas", "surface.canvas"),
    ("surfaceChrome", "surface.chrome"),
    ("surfaceChromeFallback", "surface.chromeFallback"),
    ("surfaceCard", "surface.card"),
    ("surfaceCode", "surface.code"),
    ("textMain", "text.main"),
    ("textMuted", "text.muted"),
    ("accentActive", "text.accent"),
    ("accentFill", "accent.fill"),
    ("accentTint", "accent.tint"),
    ("border", "border.default"),
    ("borderStrong", "border.strong"),
    ("specular", "border.specular"),
    ("statusNominal", "status.nominal"),
    ("statusWarning", "status.warning"),
    ("statusDanger", "status.danger"),
    ("statusSuccess", "status.success"),
    ("orb", "surface.orb"),
]

# Mode-independent brand colours, emitted as fixed values.
BRAND_ROLES = [
    "carolinaClassic",
    "carolinaWeb",
    "carolinaInk",
    "iceSpecular",
    "navyCore",
    "obsidian",
]


def snake_case(name):
    return "".join(
        ("_" if index and ch.isupper() else "") + ch.lower()
        for index, ch in enumerate(name)
    )


def load_tokens():
    return json.loads(TOKENS.read_text())


def resolve(tokens, path):
    """Resolve a colour path relative to the token file's colour groups."""
    node = tokens["color"]
    for part in path.split("."):
        node = node[part]
    return node["light"]["$value"], node["dark"]["$value"]


def rgba(value):
    """Return an (r, g, b, a) tuple of 0-255 ints from a DTCG colour value."""
    if isinstance(value, str):
        hex_ = value.lstrip("#")
        return (
            int(hex_[0:2], 16),
            int(hex_[2:4], 16),
            int(hex_[4:6], 16),
            255,
        )
    components = [round(float(component) * 255) for component in value["components"]]
    return (*components[:3], round(float(value["alpha"]) * 255))


def hex_note(value):
    r, g, b, a = rgba(value)
    if isinstance(value, str):
        return value
    alpha = a / 255
    return f"rgba({r}, {g}, {b}, {alpha:.2f})"


def swift_color_expr(rgba_value):
    r, g, b, a = rgba_value
    return (
        f"NSColor(srgbRed: {r}.0 / 255.0, green: {g}.0 / 255.0, "
        f"blue: {b}.0 / 255.0, alpha: {a}.0 / 255.0)"
    )


def generate_swift(tokens):
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Copyright (C) 2026 Stephen de la Vega.",
        "// Generated by Tools/aether7b-tokens.py — do not edit by hand.",
        f"// $source: {SOURCE_NOTE}",
        "",
        "import AppKit",
        "",
        "/// Aether7b design tokens (v1.1) for the macOS settings window.",
        "public enum XRGAether7b {",
        "    /// Adaptive and brand colours, in the sRGB colour space.",
        "    public enum Color {",
    ]
    indent = " " * 8
    for role, path in ADAPTIVE_ROLES:
        light, dark = resolve(tokens, path)
        lines.append(f"{indent}/// {role}: light {hex_note(light)}, dark {hex_note(dark)}.")
        lines.append(f"{indent}public static func {role}(dark: Bool) -> NSColor {{")
        lines.append(
            f"{indent}    let (r, g, b, a) = dark ? {tuple(rgba(dark))} : {tuple(rgba(light))}"
        )
        lines.append(
            f"{indent}    return NSColor(srgbRed: CGFloat(r) / 255.0, "
            f"green: CGFloat(g) / 255.0, blue: CGFloat(b) / 255.0, alpha: CGFloat(a) / 255.0)"
        )
        lines.append(f"{indent}}}")
        lines.append("")
    for role in BRAND_ROLES:
        value = tokens["color"]["brand"][role]["$value"]
        lines.append(f"{indent}/// Brand {role}: {hex_note(value)}.")
        lines.append(f"{indent}public static let {role} = {swift_color_expr(rgba(value))}")
        lines.append("")
    lines.extend(
        [
            "    }",
            "",
            "    /// Spacing scale (4 px base).",
            "    public enum Space {",
        ]
    )
    for name, value in space_entries(tokens):
        lines.append(f"        public static let {name}: CGFloat = {float_literal(value)}")
    lines.extend(
        [
            "    }",
            "",
            "    /// Corner radii.",
            "    public enum Radius {",
        ]
    )
    for name, value in radius_entries(tokens):
        lines.append(f"        public static let {name}: CGFloat = {float_literal(value)}")
    lines.extend(
        [
            "    }",
            "",
            "    /// Type scale entries as (size, line-height) pairs.",
            "    public enum TypeScale {",
        ]
    )
    for name, size, line_height in type_entries(tokens):
        lines.append(
            f"        public static let {name}: (size: CGFloat, lineHeight: CGFloat) "
            f"= ({float_literal(size)}, {float_literal(line_height)})"
        )
    lines.extend(
        [
            "    }",
            "",
            "    /// Motion durations in seconds and the standard easing curve.",
            "    public enum Motion {",
        ]
    )
    for name, milliseconds in duration_entries(tokens):
        lines.append(
            f"        public static let {name}: TimeInterval = {milliseconds / 1000:.3f}"
        )
    ease = ", ".join(float_literal(value) for value in ease_entries(tokens))
    lines.append(f"        public static let ease: [CGFloat] = [{ease}]")
    lines.extend(["    }", "}", ""])
    return "\n".join(lines)


def space_entries(tokens):
    scale = tokens["space"]
    entries = []
    for number in [1, 2, 3, 4, 6, 8, 12, 16]:
        value = scale[str(number)]["$value"]["value"]
        entries.append((f"s{number}", value))
    entries.append(("touchMin", scale["touchMin"]["$value"]["value"]))
    return entries


def radius_entries(tokens):
    """(name, px value) for every generated radius, read from the token file."""
    radius = tokens["radius"]
    return [(name, radius[name]["$value"]["value"]) for name in ("sm", "md", "lg")]


def duration_entries(tokens):
    """(name, milliseconds) for every generated motion duration."""
    duration = tokens["motion"]["duration"]
    return [(name, duration[name]["$value"]["value"]) for name in ("fast", "base", "slow")]


def ease_entries(tokens):
    """The standard easing curve as a list of floats."""
    return [float(value) for value in tokens["motion"]["easing"]["standard"]["$value"]]


def float_literal(value):
    """A stable, valid float literal, e.g. 1 -> 1.0, 0.22 -> 0.22, 6.5 -> 6.5.

    Works for Swift and Rust alike, and refuses non-finite values rather
    than emitting an `inf`/`nan` literal neither language accepts.
    """
    number = float(value)
    if not math.isfinite(number):
        raise ValueError(f"token value {value!r} is not a finite number")
    return repr(number)


def rust_duration_expr(milliseconds):
    """A const `Duration` expression for a token duration in milliseconds.

    `Duration::from_millis` takes a u64, so a float literal such as 140.0
    would not compile; integral values (however JSON spells them) become
    integer literals, fractional ones go through the equally const
    `from_nanos`.
    """
    millis = float(milliseconds)
    if millis.is_integer():
        return f"Duration::from_millis({int(millis)})"
    return f"Duration::from_nanos({round(millis * 1_000_000)})"


def type_entries(tokens):
    sizes = tokens["font"]["size"]
    heights = tokens["font"]["lineHeight"]
    names = [("xs", "xs"), ("sm", "sm"), ("md", "md"), ("lg", "lg"), ("xl", "xl"), ("xxl", "2xl")]
    return [
        (name, sizes[key]["$value"]["value"], heights[key]["$value"]["value"])
        for name, key in names
    ]


def rust_color_expr(rgba_value):
    r, g, b, a = rgba_value
    return f"Color32::from_rgba_unmultiplied({r}, {g}, {b}, {a})"


def generate_rust(tokens):
    lines = [
        "//! SPDX-License-Identifier: GPL-3.0-or-later",
        "//! Copyright (C) 2026 Stephen de la Vega.",
        "//! Generated by Tools/aether7b-tokens.py — do not edit by hand.",
        f"//! $source: {SOURCE_NOTE}",
        "//! Aether7b design tokens (v1.1) for the egui settings window.",
        "#![allow(dead_code)]",
        "",
        "use eframe::egui::Color32;",
        "use std::time::Duration;",
        "",
    ]
    for role, path in ADAPTIVE_ROLES:
        light, dark = resolve(tokens, path)
        name = snake_case(role)
        lines.append(f"/// {name}: light {hex_note(light)}, dark {hex_note(dark)}.")
        lines.append(f"pub fn {name}(dark: bool) -> Color32 {{")
        lines.append("    if dark {")
        lines.append(f"        {rust_color_expr(rgba(dark))}")
        lines.append("    } else {")
        lines.append(f"        {rust_color_expr(rgba(light))}")
        lines.append("    }")
        lines.append("}")
        lines.append("")
    for role in BRAND_ROLES:
        value = tokens["color"]["brand"][role]["$value"]
        lines.append(f"/// Brand {role}: {hex_note(value)}.")
        lines.append(f"pub fn brand_{snake_case(role)}() -> Color32 {{")
        lines.append(f"    {rust_color_expr(rgba(value))}")
        lines.append("}")
        lines.append("")
    for name, value in space_entries(tokens):
        lines.append(f"/// Space {name}: {value} px.")
        lines.append(f"pub const SPACE_{name.upper()}: f32 = {float_literal(value)};")
    lines.append("")
    for name, value in radius_entries(tokens):
        lines.append(f"/// Radius {name}: {value} px.")
        lines.append(f"pub const RADIUS_{name.upper()}: f32 = {float_literal(value)};")
    lines.append("")
    for name, size, line_height in type_entries(tokens):
        lines.append(f"/// Type {name}: {size} px / {line_height} px line height.")
        lines.append(
            f"pub const TYPE_{name.upper()}: (f32, f32) = "
            f"({float_literal(size)}, {float_literal(line_height)});"
        )
    lines.append("")
    for name, milliseconds in duration_entries(tokens):
        lines.append(f"/// Motion {name}: {milliseconds} ms.")
        lines.append(
            f"pub const MOTION_{name.upper()}: Duration = "
            f"{rust_duration_expr(milliseconds)};"
        )
    ease = ", ".join(float_literal(value) for value in ease_entries(tokens))
    lines.append("/// Standard easing curve (cubic-bezier from the token file).")
    lines.append(f"pub const EASE: [f32; 4] = [{ease}];")
    lines.append("")
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the generated files are current; prints a diff and exits 1 "
        "when they are stale",
    )
    args = parser.parse_args(argv)

    tokens = load_tokens()
    targets = [
        (SWIFT, generate_swift(tokens)),
        (RUST, generate_rust(tokens)),
    ]

    if not args.check:
        for path, content in targets:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content.encode("utf-8"))
            print(f"wrote {path.relative_to(ROOT)}")
        return 0

    stale = []
    for path, content in targets:
        expected = content.encode("utf-8")
        current_bytes = path.read_bytes() if path.exists() else b""
        if current_bytes != expected:
            stale.append(path)
            # Decode only for the display diff; the verdict above is on bytes.
            current = current_bytes.decode("utf-8", errors="replace")
            sys.stdout.writelines(
                difflib.unified_diff(
                    current.splitlines(keepends=True),
                    content.splitlines(keepends=True),
                    fromfile=str(path.relative_to(ROOT)),
                    tofile=str(path.relative_to(ROOT)),
                )
            )
    if stale:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
        print(
            "Generated Aether7b tokens differ; regenerate with "
            "`python3 Tools/aether7b-tokens.py`.",
            file=sys.stderr,
        )
        return 1
    print("Aether7b generated tokens are current.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())