"""Embed the shared settings catalog into XRGSharedCore as generated Swift.

The catalog ships as a string literal so the shared library needs no resource
bundle next to it on Linux. The committed JSON is kept in the exact canonical
form that is embedded. --check regenerates in memory and exits 1 with a diff
when either file is stale; without it, both files are rewritten.
"""

import argparse
import difflib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "Shared/Settings/settings-catalog.json"
GENERATED = ROOT / "Shared/Sources/XRGSharedCore/XRGSettingsCatalogData.swift"

HEADER = """// Generated by Tools/settings-catalog-embed.py from Shared/Settings/settings-catalog.json.
// Do not edit this file; regenerate it with the tool instead.
// SPDX-License-Identifier: GPL-3.0-or-later
// Copyright (C) 2026 Stephen de la Vega.

/// The settings catalog JSON, embedded so the library needs no resource bundle.
public enum XRGSettingsCatalogData {
    public static let json = #\"\"\"
"""


def canonical_json() -> str:
    data = json.loads(CATALOG.read_text(encoding="utf-8"))
    if not isinstance(data, list) or not data:
        raise SystemExit("settings-catalog.json must be a non-empty JSON array of entries")
    text = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    if '"""' in text:
        raise SystemExit("the catalog must not contain three consecutive double quotes")
    return text


def swift_source(json_text: str) -> str:
    # The empty line before the closing delimiter keeps the literal's final
    # line break, so the embedded string is the catalog file byte for byte.
    return HEADER + json_text + "\n" + '"""#\n}\n'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="verify the JSON and the generated Swift file are current")
    arguments = parser.parse_args()

    json_text = canonical_json()
    swift_text = swift_source(json_text)
    stale = []
    if arguments.check:
        if CATALOG.read_text(encoding="utf-8") != json_text:
            stale.append(str(CATALOG))
        if not GENERATED.exists() or GENERATED.read_text(encoding="utf-8") != swift_text:
            stale.append(str(GENERATED))
        if stale:
            for path in stale:
                print(f"stale: {path}")
            if GENERATED.exists():
                current = GENERATED.read_text(encoding="utf-8").splitlines(keepends=True)
                for line in difflib.unified_diff(current, swift_text.splitlines(keepends=True),
                                                 fromfile=str(GENERATED), tofile="regenerated"):
                    print(line, end="")
            else:
                print(f"missing: {GENERATED}")
            return 1
        print("settings catalog embed is current")
        return 0

    CATALOG.write_text(json_text, encoding="utf-8")
    GENERATED.write_text(swift_text, encoding="utf-8")
    print(f"embedded {len(json.loads(json_text))} catalog entries into {GENERATED}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
